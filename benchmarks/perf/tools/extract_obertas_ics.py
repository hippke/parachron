"""Extract a few Obertas, Van Laerhoven & Tamayo (2017) initial conditions into a C header.

Source data: github.com/dtamayo/spock, paper_plots/alysa-datafiles/
  initial_conditions_delta_2_to_10.npz, merged_output_files_delta_2_to_10.npz
Picks the widest-spaced systems that survived longest (those dominate the paper's compute).
Usage: python extract_obertas_ics.py /path/to/spock/paper_plots/alysa-datafiles > ../obertas_ics.h
"""
import sys
import numpy as np

d = sys.argv[1]
ic = np.load(d + "/initial_conditions_delta_2_to_10.npz")
out = np.load(d + "/merged_output_files_delta_2_to_10.npz")
delta, a, f, t_exit = ic["delta"], ic["a"], ic["f"], out["t_exit"]
idx = [i for i in np.argsort(-t_exit) if 8.0 <= delta[i] < 10.0][:4]
print("// Generated by tools/extract_obertas_ics.py from the SPOCK repository (Obertas et al. 2017 data).")
print("// Five Earth-mass planets (m = %.6e Msun) on circular coplanar orbits, G = 4 pi^2, time in yr." % ic["m_planet"])
print("#define OBERTAS_N_SYSTEMS %d" % len(idx))
print("static const double obertas_m_planet = %.17g;" % ic["m_planet"])
print("static const double obertas_delta[OBERTAS_N_SYSTEMS] = {%s};" % ", ".join("%.17g" % delta[i] for i in idx))
print("static const double obertas_t_exit[OBERTAS_N_SYSTEMS] = {%s};" % ", ".join("%.17g" % t_exit[i] for i in idx))
print("static const double obertas_a[OBERTAS_N_SYSTEMS][5] = {")
for i in idx:
    print("    {%s}," % ", ".join("%.17g" % x for x in a[:, i]))
print("};")
print("static const double obertas_f[OBERTAS_N_SYSTEMS][5] = {")
for i in idx:
    print("    {%s}," % ", ".join("%.17g" % x for x in f[:, i]))
print("};")
